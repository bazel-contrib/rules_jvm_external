package com.github.bazelbuild.rules_jvm_external.resolver.lockfile;

import java.util.ArrayList;
import java.util.Comparator;
import java.util.List;
import java.util.Map;

/** Renders v3 resolver results and a canonical input snapshot as a v4 lock file. */
public final class V4LockFile {
  private V4LockFile() {}

  public static String render(Map<String, Object> v3, Map<String, Object> inputs) {
    return render(v3, inputs, false);
  }

  public static String render(
      Map<String, Object> v3, Map<String, Object> inputs, boolean includeFiles) {
    V4Artifacts graph = new V4Artifacts(v3);
    List<V4Artifact> records = new ArrayList<>(graph.byIdentity.values());
    records.sort(Comparator.comparing(V4Artifact::externalForm));
    List<Map<String, Object>> unresolved =
        V4Requests.attach(records, V4Json.items(inputs.get("artifacts")));
    List<String> lines = new ArrayList<>();
    lines.add("{");
    append(
        lines,
        "__AUTOGENERATED_FILE_DO_NOT_MODIFY_THIS_FILE_MANUALLY",
        "THERE_IS_NO_DATA_ONLY_ZUUL");
    lines.add("  \"artifacts\": [");
    for (int i = 0; i < records.size(); i++) {
      V4Artifact record = records.get(i);
      String identity = record.coordinates.asKey();
      lines.add(
          "    "
              + V4Json.compact(
                  record.row(
                      graph.dependencies.getOrDefault(identity, List.of()),
                      graph.local.contains(identity),
                      graph.skipped.contains(identity)))
              + (i + 1 < records.size() ? "," : ""));
      if (i + 1 < records.size()) {
        // Unchanged separators let Git merge adjacent dependency updates independently.
        lines.add("");
      }
    }
    lines.add("  ],");
    append(lines, "boms", inputs.getOrDefault("boms", List.of()));
    append(lines, "conflict_resolution", v3.get("conflict_resolution"));
    append(lines, "dependencies", graph.dependencies);
    if (includeFiles) {
      append(lines, "files", v3.get("files"));
    }
    if (Boolean.TRUE.equals(v3.get("m2local"))) {
      append(lines, "m2local", true);
      append(lines, "m2local_artifacts", graph.local);
    }
    append(lines, "packages", v3.get("packages"));
    lines.add("  \"repositories\": " + V4Json.prettyInOrder(graph.repositories) + ",");
    append(lines, "services", v3.get("services"));
    append(lines, "settings", inputs.getOrDefault("settings", Map.of()));
    if (v3.containsKey("skipped")) {
      append(lines, "skipped", graph.skipped);
    }
    append(lines, "unresolved_requests", unresolved);
    lines.add("  \"version\": \"4\"");
    lines.add("}");
    return String.join("\n", lines) + "\n";
  }

  private static void append(List<String> lines, String key, Object value) {
    if (value != null) {
      lines.add("  " + V4Json.compact(key) + ": " + V4Json.pretty(value) + ",");
    }
  }
}
